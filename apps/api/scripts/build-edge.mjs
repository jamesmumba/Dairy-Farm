// Bundles the API for Supabase Edge Functions:  npm run build:edge
// Our TypeScript becomes one ES module; npm packages stay external as Deno `npm:` imports,
// pinned to the exact versions installed here, so the function runs what the tests ran.

import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, '../../supabase/functions/api/index.js');

const installedVersion = (pkg) => JSON.parse(readFileSync(join(root, 'node_modules', pkg, 'package.json'), 'utf8')).version;

const npmSpecifiers = {
  name: 'npm-specifiers',
  setup(b) {
    // Bare package names only: not relative paths, and not absolute paths (C:\… on Windows).
    b.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.kind === 'entry-point' || /^[A-Za-z]:[\\/]/.test(args.path)) return undefined;
      if (args.path.startsWith('node:')) return { path: args.path, external: true };
      const parts = args.path.split('/');
      const pkg = args.path.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
      const sub = args.path.slice(pkg.length);
      return { path: `npm:${pkg}@${installedVersion(pkg)}${sub}`, external: true };
    });
  },
};

await build({
  entryPoints: [join(root, 'src/edge.ts')],
  outfile: out,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  plugins: [npmSpecifiers],
  banner: { js: '// GENERATED by apps/api/scripts/build-edge.mjs from apps/api/src — do not edit by hand.' },
  logLevel: 'info',
});
